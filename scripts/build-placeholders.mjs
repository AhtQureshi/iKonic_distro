// Builds src/data/placeholders.generated.js: a tiny blurred preview (inline data URI, a few hundred bytes)
// of each page banner in public/assets/images/, shown behind the banner until the full photo arrives.
// Run `npm run placeholders` after adding or changing a banner, and commit the result.
// Not run on build: it needs sharp, which is only guaranteed locally.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const IMAGES = join(ROOT, 'public', 'assets', 'images');
const OUT = join(ROOT, 'src', 'data', 'placeholders.generated.js');

// Banners rendered with `priority` at the top of a page.
const FILES = [
  'hero-studio.webp',
  'advance-hero.webp',
  'contact-hero.webp',
  'distribution-hero.webp',
  'pricing-hero.webp',
  'publishing-hero.webp',
];

const entries = await Promise.all(FILES.map(async (file) => {
  const data = await sharp(join(IMAGES, file)).resize(32).webp({ quality: 60 }).toBuffer();
  return `  '${file}': 'data:image/webp;base64,${data.toString('base64')}',`;
}));

const content =
  '// GENERATED by scripts/build-placeholders.mjs from public/assets/images/. Do not edit.\n' +
  '// After adding or changing a banner, run `npm run placeholders`.\n' +
  `export const PLACEHOLDERS = {\n${entries.join('\n')}\n};\n`;

if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== content) writeFileSync(OUT, content);
console.log(`placeholders: ${entries.length}`);
